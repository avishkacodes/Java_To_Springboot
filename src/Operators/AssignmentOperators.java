package Operators;

public class AssignmentOperators {

    public static void main(String[] args) {

        int num1 = 25;
        int num2 = 30;

        int res = num1;

        System.out.println(res);

        res += num2;
        System.out.println(res);

        res -= num2;
        System.out.println(res);

        res *= num2;
        System.out.println(res);

        res /= num2;
        System.out.println(res);

//        res %= num2;
//        System.out.println(res);

    }
}
